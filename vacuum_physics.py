import numpy as np


def get_combined_knudsen(lambda_0, R, M_bar, z0_profile=None, M_bh=0.0):
    """
    Локальное полевое число Кнудсена вакуумной среды (без привязки к геометрии диска).
    
    Физический смысл:
    Вместо поверхностной плотности диска (M_bar / (2 * pi * R * z0)) используется
    локальная полевая поверхностная плотность Sigma_field = a_newton / G ~ M_total / R^2,
    имеющая ту же размерность [кг/м^2].
    """
    R_safe = np.maximum(R, 1e-3)
    
    # Полная барионная масса внутри радиуса R (звезды + газ + центральная ЧД)
    # M_bh передается в единицах 10^9 M_sun, переводим в M_sun для единой шкалы с M_bar
    M_total = np.maximum(M_bar + (M_bh * 1e9), 1e-6)
    
    # Локальная полевая плотность потока импульса (аналог Sigma_field = a_newton / G)
    sigma_field = M_total / (4.0 * np.pi * R_safe**2)
    sigma_field = np.maximum(sigma_field, 1e-25)
    
    # Локальное число Кнудсена: отношение критического порога поляризации к напряженности поля
    return lambda_0 / sigma_field


def model_velocity_knudsen(params, R, Vbar, M_bar, R_d, z_c, M_bh, alpha):
    """
    Расчет модельной кривой вращения галактики в рамках локальной упруго-поляризационной
    модели вакуума (без искусственного фазового замерзания и глобальных параметров диска).
    
    Параметры R_d и z_c оставлены в сигнатуре исключительно для обратной совместимости
    с вызывающим кодом (streamlit_app.py) и в расчетах не участвуют.
    """
    k_shear, lambda_0, *_ = params
    
    # Базовое пороговое ускорение сдвиговой упругости вакуума [(км/с)^2 / кпк]
    a0_base = 3600.0 * k_shear
    
    G_CONST = 4.30091e-6  # kpc * (km/s)^2 / M_sun
    R_safe = np.maximum(R, 1e-3)
    
    # Классическое ньютоновское ускорение (барионный диск/газ + центральная ЧД)
    a_bh = (G_CONST * (M_bh * 1e9)) / (R_safe**2)
    a_newton = (Vbar**2 / R_safe) + a_bh
    a_newton = np.maximum(a_newton, 1e-12)
    
    # Расчет чисто локального полевого числа Кнудсена
    Kn = get_combined_knudsen(lambda_0, R_safe, M_bar, M_bh=M_bh)
    
    # Эффективное сдвиговое ускорение вакуума:
    # - в плотном центре (Kn -> 0) переходит в константу a0_base (при alpha=0)
    # - на сверхдальних дистанциях (Kn >> 1) плавно затухает через exp(-Kn),
    #   решая проблему расходимости массы гало на бесконечности
    Kn_safe = np.maximum(Kn, 1e-6)
    a_eff = (a0_base / (1.0 + Kn)) * (1.0 / (Kn_safe**alpha)) * np.exp(-Kn)
    
    # Полное ускорение (интерполяционное решение для сдвигового девиатора вакуума)
    a_total = (a_newton + np.sqrt(a_newton**2 + 4.0 * a_newton * a_eff)) / 2.0
    
    # Итоговая орбитальная скорость (км/с)
    V_mod = np.sqrt(np.maximum(a_total * R_safe, 0.0))
    
    return V_mod
